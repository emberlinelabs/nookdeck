// Writes src/platform/mra-embed.gen.ts: the MediaRemote adapter (see vendor/mediaremote-adapter) as files `bun build --compile`
// embeds. Without a built framework (other OS, no clang yet) it writes a stub exporting null, and Nookdeck then reads Now Playing
// from Spotify and Music only.
import { existsSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

export const MRA_ROOT = join(import.meta.dir, "..");
export const MRA_BUILT = join(MRA_ROOT, "build", "mediaremote", "MediaRemoteAdapter");
const OUT = join(MRA_ROOT, "src", "platform", "mra-embed.gen.ts");
const SCRIPT = join(MRA_ROOT, "vendor", "mediaremote-adapter", "bin", "mediaremote-adapter.pl");

export function writeMraEmbed(): boolean {
  const have = existsSync(MRA_BUILT) && existsSync(SCRIPT);
  const rel = (p: string) => relative(join(MRA_ROOT, "src", "platform"), p).split("\\").join("/");
  const body = have
    ? `import binary from "${rel(MRA_BUILT)}" with { type: "file" };\nimport script from "${rel(SCRIPT)}" with { type: "file" };\nexport const MRA_EMBED: { binary: string; script: string } | null = { binary, script };\n`
    : `export const MRA_EMBED: { binary: string; script: string } | null = null;\n`;
  writeFileSync(OUT, `// @ts-nocheck - generated by scripts/mra-assets.ts, do not edit\n${body}`);
  return have;
}

if (import.meta.main) console.log(writeMraEmbed() ? "mra-embed.gen.ts: adapter embedded" : "mra-embed.gen.ts: no adapter built (stub)");
