export function translate(lang: Language, key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang];
  let s = dict ? dict[key] ?? key : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

