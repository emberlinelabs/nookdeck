/**
 * Tiny i18n for the agent's user-facing strings (errors sent to phones and the management page, notify texts, CLI).
 * The key IS the English text, so code stays readable and a missing translation falls back to English.
 * Placeholders are `{name}`. The language follows layout `theme.language` ("en" default; "vi", "zh", "fr" and "pt" extra, pt is
 * written as Brazilian Portuguese). The CLI follows the terminal's locale (localeLanguage).
 */
export type Language = "en" | "vi" | "zh" | "fr" | "pt";
const EXTRA = ["vi", "zh", "fr", "pt"] as const;

let current: Language = "en";

export const setLanguage = (l: unknown): void => { current = (EXTRA as readonly unknown[]).includes(l) ? (l as Language) : "en"; };

/** The language of a locale name such as "fr_FR.UTF-8", "pt-BR" or "zh_CN": fr*, pt* (pt-BR and pt-PT), vi*, zh*, else English. */
export function languageOfLocale(locale: string | undefined | null): Language {
  const m = /^\s*([a-z]{2,3})(?:[-_.@]|$)/i.exec(locale ?? "");
  const code = m?.[1]!.toLowerCase();
  return code && (EXTRA as readonly string[]).includes(code) ? (code as Language) : "en";
}

/** The terminal's language, from LC_ALL, then LC_MESSAGES, then LANG (POSIX order); "C" or "POSIX" mean English. */
export function localeLanguage(env: Record<string, string | undefined> = process.env): Language {
  const v = [env.LC_ALL, env.LC_MESSAGES, env.LANG].find((x) => !!x && x.trim() !== "");
  return languageOfLocale(v);
}
export const getLanguage = (): Language => current;

